const messages: Record<AppLocale, Record<TranslationKey, string>> = {
  en,
  'zh-CN': zh,
};

interface I18nValue {
  locale: AppLocale;
  setLocale(locale: AppLocale): void;
  t(key: TranslationKey, values?: Record<string, string | number>): string;
  commandLabel(command: string): string;
}

const I18nContext = createContext<I18nValue | null>(null);

function getInitialLocale(): AppLocale {
  try {
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'zh-CN') return stored;
  } catch {
    // Storage can be unavailable in restricted renderer contexts.
  }
  return window.navigator.language.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

function interpolate(template: string, values?: Record<string, string | number>): string {
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : match,
  );
}

export function I18nProvider({ children }: { children: ReactNode }): ReactNode {
  const [locale, setLocale] = useState<AppLocale>(getInitialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    try {
      window.localStorage.setItem(STORAGE_KEY, locale);
    } catch {
      // The UI still works when persistent storage is unavailable.
    }
    window.pixel?.setLocale(locale);
  }, [locale]);

  const t = useCallback(
    (key: TranslationKey, values?: Record<string, string | number>) =>
      interpolate(messages[locale][key] ?? messages.en[key], values),
    [locale],
  );

  const commandLabel = useCallback(
    (command: string) => {
      const key = `command.${command}` as TranslationKey;
      if (Object.hasOwn(messages[locale], key)) return messages[locale][key];
      return messages.en[key] ?? command.replaceAll('_', ' ');
    },
    [locale],
  );

  const value = useMemo(
    () => ({ locale, setLocale, t, commandLabel }),
    [locale, t, commandLabel],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside <I18nProvider>');
  return value;
}
